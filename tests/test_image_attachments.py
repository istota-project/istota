    def test_text_over_the_per_image_share_is_truncated_and_marked(
        self, tmp_path, monkeypatch, ocr_calls
    ):
        src = _png(tmp_path / "dense.png")
        monkeypatch.setattr(image_attachments, "OCR_MAX_CHARS_PER_IMAGE", 50)
        ocr_calls.state["reply"] = lambda p: {
            "status": "ok", "text": "x" * 500, "confidence": 0.8, "word_count": 100,
        }

        prep = _prep([src], tmp_path)

        block = _block(prep, "dense.png")
        assert block.kind == KIND_TRUNCATED
        assert len(block.text) == 50

    def test_the_per_image_share_shrinks_with_the_image_count(self, tmp_path, ocr_calls):
        srcs = [_png(tmp_path / f"d{n}.png") for n in range(20)]
        ocr_calls.state["reply"] = lambda p: {
            "status": "ok", "text": "y" * 20_000, "confidence": 0.8, "word_count": 1,
        }

        prep = _prep(srcs, tmp_path)

        share = image_attachments.OCR_MAX_CHARS_TOTAL // 20
        assert all(len(b.text) <= share for b in prep.ocr_blocks)
        assert sum(len(b.text) for b in prep.ocr_blocks) <= (
            image_attachments.OCR_MAX_CHARS_TOTAL
        )

    def test_a_dense_first_image_cannot_starve_the_later_ones(self, tmp_path, ocr_calls):
        """Why the per-image share exists, and why the budget notice never fires.

        A flat 12,000 per image against a 48,000 task total would let four
        dense pages consume everything and leave images 5 through 20 rendering
        empty blocks. `min(cap, total // count)` floors, so the shares cannot
        sum past the total — which makes `KIND_BUDGET` an invariant guard
        rather than a reachable branch. Its rendering is pinned in
        `TestRendering`; this pins the property that keeps it unreached.
        """
        srcs = [_png(tmp_path / f"e{n}.png") for n in range(5)]
        ocr_calls.state["reply"] = lambda p: {
            "status": "ok", "text": "z" * 30_000, "confidence": 0.8, "word_count": 1,
        }

        prep = _prep(srcs, tmp_path)

        share = min(
            image_attachments.OCR_MAX_CHARS_PER_IMAGE,
            image_attachments.OCR_MAX_CHARS_TOTAL // 5,
        )
        assert [b.kind for b in prep.ocr_blocks] == [KIND_TRUNCATED] * 5
        assert [len(b.text) for b in prep.ocr_blocks] == [share] * 5
        assert sum(len(b.text) for b in prep.ocr_blocks) <= (
            image_attachments.OCR_MAX_CHARS_TOTAL
        )
        assert KIND_BUDGET not in [b.kind for b in prep.ocr_blocks]

    def test_an_exhausted_ocr_deadline_keeps_the_completed_blocks(
        self, tmp_path, monkeypatch, ocr_calls
    ):
        srcs = [_png(tmp_path / f"t{n}.png") for n in range(3)]
        clock = {"t": 0.0}

        def reply(p):
            clock["t"] += 40.0
            return {"status": "ok", "text": "some text", "confidence": 0.9, "word_count": 2}

        ocr_calls.state["reply"] = reply
        monkeypatch.setattr(
            image_attachments, "time", SimpleNamespace(monotonic=lambda: clock["t"])
        )

        prep = _prep(srcs, tmp_path)

        assert len(prep.images) == 3
        assert prep.ocr_blocks[0].kind == KIND_TEXT
        assert prep.ocr_blocks[-1].kind == KIND_UNAVAILABLE
        assert "deadline" in prep.ocr_blocks[-1].detail

    def test_the_remaining_deadline_is_handed_to_each_child(self, tmp_path, ocr_calls):
        srcs = [_png(tmp_path / f"r{n}.png") for n in range(2)]

        _prep(srcs, tmp_path)

        assert all(0 < c[1] <= image_attachments.OCR_TOTAL_TIMEOUT_SECONDS for c in ocr_calls)

    def test_an_omitted_image_still_gets_a_block_and_no_ocr_call(self, tmp_path, ocr_calls):
        good = _png(tmp_path / "good.png")
        bad = tmp_path / "bad.png"
        bad.write_text("nope")

        prep = _prep([good, bad], tmp_path)

        assert len(ocr_calls) == 1
        assert [b.display_name for b in prep.ocr_blocks] == ["good.png", "bad.png"]
        assert _block(prep, "bad.png").kind == KIND_OMITTED


