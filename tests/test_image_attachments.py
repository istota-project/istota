def _noise(size):
    """A photo-like image that does not compress to nothing."""
    w, h = size
    return Image.frombytes("RGB", size, os.urandom(w * h * 3))


def _png(path: Path, size=(64, 48), color=(10, 20, 30), mode="RGB") -> Path:
    Image.new(mode, size, color).save(path, "PNG")
    return path


def _jpeg(path: Path, size=(64, 48), exif_orientation=None) -> Path:
    img = _noise(size)
    kwargs = {}
    if exif_orientation is not None:
        exif = Image.Exif()
        exif[0x0112] = exif_orientation
        kwargs["exif"] = exif
    img.save(path, "JPEG", quality=90, **kwargs)
    return path


def _rgba_png(path: Path, size=(64, 48)) -> Path:
    # Fully transparent over near-black pixels: exactly the dark-mode
    # screenshot that reaches Tesseract as black-on-black if alpha is dropped
    # without flattening.
    img = Image.new("RGBA", size, (4, 4, 4, 0))
    img.save(path, "PNG")
    return path


class _Calls(list):
    """The recorded `(path, timeout)` calls, plus the reply the stub gives.

    A list subclass rather than a tuple of two objects, so a test reads
    `ocr_calls[0][0]` for the path it was handed and sets
    `ocr_calls.state["reply"]` when it wants a different answer.
    """

    state: dict


@pytest.fixture
def ocr_calls(monkeypatch):
    """Stub the OCR child boundary; record `(path, timeout)` per call.

    Autouse would hide the seam, so every test that expects OCR asks for this
    fixture by name.
    """
    calls = _Calls()
    calls.state = {
        "reply": lambda path: {
            "status": "ok", "text": "Hello World", "confidence": 0.94, "word_count": 2,
        }
    }

    def fake(path, timeout=60.0):
        calls.append((path, timeout))
        return calls.state["reply"](path)

    monkeypatch.setattr(image_attachments, "ocr_image_out_of_process", fake)
    return calls


@pytest.fixture
def no_ocr(monkeypatch):
    """Refuse to let a test spawn Tesseract without saying so."""
    def fake(path, timeout=60.0):
        return {"status": "ok", "text": "", "confidence": 0, "word_count": 0}

    monkeypatch.setattr(image_attachments, "ocr_image_out_of_process", fake)


def _prep(attachments, tmp_path, task_id=7, cancel_check=None) -> ImagePreparation:
    return prepare_image_attachments(
        [str(a) for a in attachments],
        tmp_path / "usertmp",
        task_id,
        cancel_check=cancel_check,
    )


def _block(prep: ImagePreparation, name: str):
    for b in prep.ocr_blocks:
        if b.display_name == name:
            return b
    raise AssertionError(f"no OCR block for {name}: {[b.display_name for b in prep.ocr_blocks]}")


