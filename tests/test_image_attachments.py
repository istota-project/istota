class TestMultiFrame:
    def test_an_animated_gif_uses_the_first_frame_and_names_the_dropped_ones(
        self, tmp_path, ocr_calls
    ):
        src = tmp_path / "anim.gif"
        # Visibly different frames: the GIF writer drops a frame whose delta
        # against its predecessor is empty, so four identically-rendering
        # palette images would be written as one.
        frames = [
            Image.new("RGB", (64, 48), (n * 60, 255 - n * 60, 40)).convert("P")
            for n in range(4)
        ]
        frames[0].save(src, save_all=True, append_images=frames[1:], duration=80, loop=0)

        prep = _prep([src], tmp_path)

        assert len(prep.images) == 1
        note = _block(prep, "anim.gif").note
        assert "3" in note and "frame" in note

    def test_a_multipage_tiff_uses_the_first_page_and_says_pages_not_frames(
        self, tmp_path, ocr_calls
    ):
        """A 12-page scanned contract must not arrive as page 1 in silence."""
        src = tmp_path / "contract.tiff"
        pages = [Image.new("RGB", (64, 48), (i * 20, 0, 0)) for i in range(12)]
        pages[0].save(src, save_all=True, append_images=pages[1:])

        prep = _prep([src], tmp_path)

        assert len(prep.images) == 1
        note = _block(prep, "contract.tiff").note
        assert "11" in note and "page" in note

    def test_a_single_frame_image_gets_no_dropped_frame_notice(self, tmp_path, ocr_calls):
        src = _png(tmp_path / "still.png")

        prep = _prep([src], tmp_path)

        assert _block(prep, "still.png").note == ""


