class TestLimits:
    def test_the_fixed_budgets_are_the_ones_the_spec_names(self):
        assert image_attachments.MAX_IMAGES == 20
        assert image_attachments.MAX_SOURCE_BYTES == 64 * 1024 * 1024
        assert image_attachments.MAX_SOURCE_PIXELS == 50_000_000
        assert image_attachments.MAX_NORMALIZE_SECONDS == 180.0
        assert image_attachments.MAX_ENCODED_BYTES == 8 * 1024 * 1024
        assert image_attachments.MAX_EDGE == 1568
        assert image_attachments.MAX_AREA_PIXELS == 1_150_000
        assert image_attachments.OCR_TOTAL_TIMEOUT_SECONDS == 60.0
        assert image_attachments.OCR_MAX_CHARS_PER_IMAGE == 12_000
        assert image_attachments.OCR_MAX_CHARS_TOTAL == 48_000

    def test_the_inbound_extension_set_is_the_ten_the_spec_names(self):
        assert IMAGE_EXTENSIONS == frozenset(
            {"jpg", "jpeg", "png", "webp", "gif", "bmp", "tiff", "tif", "heic", "heif"}
        )

    def test_encoded_length_is_base64_inflation_not_file_bytes(self):
        for n in (0, 1, 2, 3, 4, 999, 100_000):
            assert encoded_len(n) == len(base64.b64encode(b"x" * n))

    @pytest.mark.parametrize(
        "source",
        [
            Path(image_attachments.__file__),
            Path(__file__),
        ],
    )
    def test_nothing_mutates_pillow_process_globals(self, source):
        """A module global or a warnings filter would race a concurrent task.

        `avatars.py` records the same reasoning; the per-call `img.size` check
        is the pattern instead. Needles are assembled so this scan does not
        match itself.
        """
        text = source.read_text()
        for needle in ("MAX_IMAGE" + "_PIXELS", "simple" + "filter", "catch_" + "warnings"):
            assert needle not in text, f"{source.name} touches {needle}"


