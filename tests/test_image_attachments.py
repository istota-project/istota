"""Tests for `istota.image_attachments` — inbound image preparation and OCR.

Every image fixture here is generated by Pillow in the test, so nothing in the
repository carries picture bytes. The OCR child process is stubbed at its own
module boundary (`ocr_image_out_of_process`), which is the coarse seam: the
runner itself has its own tests in `tests/test_transcribe_out_of_process.py`.

Two properties are asserted about the tests as much as about the code. Nothing
here — and nothing in the module — writes Pillow's decompression-bomb module
global or installs a warnings filter, because both are process-wide and
`execute_task` runs on a worker thread. And the model-facing notices name only
basenames, never the directory an attachment came from.
"""

