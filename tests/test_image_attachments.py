class TestPreDecodeGates:
    def test_an_oversize_source_is_refused_without_opening_it(
        self, tmp_path, monkeypatch, no_ocr
    ):
        big = _png(tmp_path / "huge.png", size=(256, 256))
        monkeypatch.setattr(image_attachments, "MAX_SOURCE_BYTES", 16)

        def boom(*a, **k):
            raise AssertionError("Image.open ran on a file refused by the size gate")

        monkeypatch.setattr("PIL.Image.open", boom)

        prep = _prep([big], tmp_path)

        assert prep.images == []
        block = _block(prep, "huge.png")
        assert block.kind == KIND_OMITTED
        assert "too large" in block.detail

    def test_a_header_declaring_too_many_pixels_is_refused_before_decoding(
        self, tmp_path, monkeypatch, no_ocr
    ):
        img = _png(tmp_path / "wide.png", size=(200, 200))
        monkeypatch.setattr(image_attachments, "MAX_SOURCE_PIXELS", 100)

        def boom(*a, **k):
            raise AssertionError("the image was decoded despite the pixel gate")

        monkeypatch.setattr(ImageOps, "exif_transpose", boom)

        prep = _prep([img], tmp_path)

        assert prep.images == []
        block = _block(prep, "wide.png")
        assert block.kind == KIND_OMITTED
        assert "pixel" in block.detail

    def test_a_decompression_bomb_error_is_caught_by_name(self, tmp_path, monkeypatch, no_ocr):
        img = _png(tmp_path / "bomb.png")

        def raise_bomb(*a, **k):
            raise Image.DecompressionBombError("too many pixels")

        monkeypatch.setattr("PIL.Image.open", raise_bomb)

        prep = _prep([img], tmp_path)

        assert prep.images == []
        block = _block(prep, "bomb.png")
        assert block.kind == KIND_OMITTED
        assert "pixel" in block.detail

    def test_the_size_gate_reads_the_file_not_the_decoded_image(self, tmp_path, no_ocr):
        """A file inside the byte gate is admitted even though it is not tiny."""
        img = _jpeg(tmp_path / "ok.jpg", size=(300, 200))
        assert img.stat().st_size < image_attachments.MAX_SOURCE_BYTES

        prep = _prep([img], tmp_path)

        assert [i.display_name for i in prep.images] == ["ok.jpg"]


