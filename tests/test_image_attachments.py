class TestNormalization:
    def test_a_small_in_limits_png_needs_no_rewrite(self, tmp_path, ocr_calls):
        src = _png(tmp_path / "small.png")

        prep = _prep([src], tmp_path)

        assert prep.attachments == [str(src.resolve())]
        assert len(prep.images) == 1
        assert prep.images[0].path == src.resolve()
        assert prep.images[0].media_type == "image/png"

    def test_every_prepared_path_is_resolved(self, tmp_path, ocr_calls):
        link_dir = tmp_path / "link"
        real = tmp_path / "real"
        real.mkdir()
        link_dir.symlink_to(real)
        src = _png(real / "s.png")

        prep = _prep([link_dir / "s.png"], tmp_path)

        assert prep.images[0].path == src.resolve()
        assert prep.images[0].path.is_absolute()
        assert prep.attachments == [str(src.resolve())]

    def test_an_oversized_image_is_bounded_by_both_the_edge_and_the_area(
        self, tmp_path, ocr_calls
    ):
        src = _jpeg(tmp_path / "pano.jpg", size=(3000, 2000))

        prep = _prep([src], tmp_path)

        with Image.open(prep.images[0].path) as out:
            w, h = out.size
        assert max(w, h) <= image_attachments.MAX_EDGE
        assert w * h <= image_attachments.MAX_AREA_PIXELS

    def test_the_area_cap_is_enforced_here_not_delegated_to_the_provider(
        self, tmp_path, ocr_calls
    ):
        """A 1500x1500 square is inside the long edge and outside the area cap."""
        src = _jpeg(tmp_path / "square.jpg", size=(1500, 1500))

        prep = _prep([src], tmp_path)

        with Image.open(prep.images[0].path) as out:
            w, h = out.size
        assert max(w, h) <= image_attachments.MAX_EDGE
        assert w * h <= image_attachments.MAX_AREA_PIXELS
        assert w < 1500

    def test_exif_orientation_is_materialized(self, tmp_path, ocr_calls):
        # Orientation 6 swaps the axes: a 120x60 landscape becomes 60x120.
        src = _jpeg(tmp_path / "rotated.jpg", size=(120, 60), exif_orientation=6)

        prep = _prep([src], tmp_path)

        with Image.open(prep.images[0].path) as out:
            assert out.size == (60, 120)
            assert out.getexif().get(0x0112, 1) in (0, 1)

    def test_the_normalized_copy_lands_in_the_task_temp_directory(self, tmp_path, ocr_calls):
        src = _jpeg(tmp_path / "pano.jpg", size=(3000, 2000))

        prep = _prep([src], tmp_path, task_id=42)

        out = prep.images[0].path
        assert out.parent == (tmp_path / "usertmp" / "attachments" / "task_42").resolve()

    def test_two_files_sharing_a_stem_do_not_overwrite_each_other(self, tmp_path, ocr_calls):
        one = tmp_path / "one"
        two = tmp_path / "two"
        one.mkdir()
        two.mkdir()
        a = _jpeg(one / "IMG_1234.jpg", size=(2400, 1800))
        b = _jpeg(two / "IMG_1234.jpg", size=(2400, 1800))

        prep = _prep([a, b], tmp_path)

        assert len(prep.images) == 2
        assert prep.images[0].path != prep.images[1].path


class TestOutputFormat:
    @pytest.mark.parametrize(
        "save_format,suffix,expected_media_type",
        [
            ("PNG", ".png", "image/png"),
            ("BMP", ".bmp", "image/png"),
            ("TIFF", ".tiff", "image/png"),
            ("GIF", ".gif", "image/png"),
            ("WEBP", ".webp", "image/webp"),
            ("JPEG", ".jpg", "image/jpeg"),
        ],
    )
    def test_the_output_format_follows_the_source_class(
        self, tmp_path, ocr_calls, save_format, suffix, expected_media_type
    ):
        src = tmp_path / f"in{suffix}"
        # Oversized, so every case actually re-encodes and the media type is
        # the one the rewrite chose rather than the one the source happened to
        # have.
        _noise((2000, 1600)).save(src, save_format)

        prep = _prep([src], tmp_path)

        assert prep.images[0].media_type == expected_media_type
        with Image.open(prep.images[0].path) as out:
            assert out.format == expected_media_type.split("/")[1].upper()

    def test_a_bmp_is_converted_even_when_it_needs_no_resize(self, tmp_path, ocr_calls):
        """BMP is outside every provider's accepted set, so conversion is required."""
        src = tmp_path / "tiny.bmp"
        Image.new("RGB", (40, 30), (1, 2, 3)).save(src, "BMP")

        prep = _prep([src], tmp_path)

        assert prep.images[0].media_type == "image/png"
        assert prep.images[0].path != src.resolve()

    def test_only_provider_accepted_media_types_are_emitted(self, tmp_path, ocr_calls):
        srcs = []
        for fmt, suffix in [("PNG", ".png"), ("WEBP", ".webp"), ("JPEG", ".jpg"),
                            ("BMP", ".bmp"), ("TIFF", ".tif"), ("GIF", ".gif")]:
            p = tmp_path / f"x{suffix}"
            Image.new("RGB", (40, 30), (9, 9, 9)).save(p, fmt)
            srcs.append(p)

        prep = _prep(srcs, tmp_path)

        assert {i.media_type for i in prep.images} <= {
            "image/png", "image/jpeg", "image/webp",
        }

    def test_a_webp_stays_webp_rather_than_inflating_into_png(self, tmp_path, ocr_calls):
        src = tmp_path / "shot.webp"
        _noise((2000, 1600)).save(src, "WEBP", quality=80)

        prep = _prep([src], tmp_path)

        assert prep.images[0].media_type == "image/webp"

    def test_a_screenshot_stays_png_so_ocr_does_not_read_jpeg_ringing(
        self, tmp_path, ocr_calls
    ):
        src = tmp_path / "shot.png"
        Image.new("RGB", (2000, 1600), (255, 255, 255)).save(src, "PNG")

        prep = _prep([src], tmp_path)

        assert prep.images[0].media_type == "image/png"
        ocr_path = ocr_calls[0][0]
        with Image.open(ocr_path) as out:
            assert out.format == "PNG"

    def test_an_icc_profile_survives_the_rewrite(self, tmp_path, ocr_calls):
        profile = b"fake-icc-profile-bytes"
        src = tmp_path / "wide.jpg"
        _noise((2000, 1600)).save(src, "JPEG", icc_profile=profile)

        prep = _prep([src], tmp_path)

        with Image.open(prep.images[0].path) as out:
            assert out.info.get("icc_profile") == profile


class TestAlpha:
    def test_the_vision_rendition_keeps_alpha_for_a_png(self, tmp_path, ocr_calls):
        src = _rgba_png(tmp_path / "dark.png")

