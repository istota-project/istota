class TestScreening:
    def test_no_attachments_is_a_no_op(self, tmp_path):
        prep = prepare_image_attachments(None, tmp_path, 1)
        assert prep.attachments is None
        assert prep.images == []
        assert prep.ocr_blocks == []

    def test_a_non_image_attachment_is_left_exactly_as_it_arrived(self, tmp_path, no_ocr):
        pdf = tmp_path / "report.pdf"
        pdf.write_bytes(b"%PDF-1.4\n")

        prep = _prep([pdf], tmp_path)

        assert prep.attachments == [str(pdf)]
        assert prep.images == []
        assert prep.ocr_blocks == []

    def test_an_image_without_a_recognized_extension_is_an_ordinary_attachment(
        self, tmp_path, no_ocr
    ):
        odd = tmp_path / "photo.dat"
        _png(odd)

        prep = _prep([odd], tmp_path)

        assert prep.attachments == [str(odd)]
        assert prep.images == []

    def test_mixed_attachments_keep_sender_order(self, tmp_path, ocr_calls):
        a = _png(tmp_path / "a.png")
        doc = tmp_path / "b.pdf"
        doc.write_bytes(b"%PDF")
        c = _png(tmp_path / "c.png")

        prep = _prep([a, doc, c], tmp_path)

        assert len(prep.attachments) == 3
        assert prep.attachments[1] == str(doc)
        assert [i.display_name for i in prep.images] == ["a.png", "c.png"]
        assert [b.display_name for b in prep.ocr_blocks] == ["a.png", "c.png"]

    def test_a_renamed_non_image_is_reported_undecodable_and_stays_an_attachment(
        self, tmp_path, no_ocr
    ):
        fake = tmp_path / "invoice.png"
        fake.write_text("this is not an image at all")

        prep = _prep([fake], tmp_path)

        assert prep.attachments == [str(fake)]
        assert prep.images == []
        block = _block(prep, "invoice.png")
        assert block.kind == KIND_OMITTED
        assert "decode" in block.detail

    def test_corrupt_image_bytes_are_reported_rather_than_raised(self, tmp_path, no_ocr):
        broken = tmp_path / "broken.png"
        broken.write_bytes(b"\x89PNG\r\n\x1a\n" + b"\x00" * 40)

        prep = _prep([broken], tmp_path)

        assert prep.images == []
        assert _block(prep, "broken.png").kind == KIND_OMITTED

    def test_a_missing_file_is_reported_rather_than_raised(self, tmp_path, no_ocr):
        gone = tmp_path / "gone.png"

        prep = _prep([gone], tmp_path)

        assert prep.attachments == [str(gone)]
        assert prep.images == []
        assert _block(prep, "gone.png").kind == KIND_OMITTED


