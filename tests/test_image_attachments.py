class TestBudgets:
    def test_more_than_twenty_images_leaves_the_rest_as_plain_attachments(
        self, tmp_path, ocr_calls
    ):
        srcs = [_png(tmp_path / f"i{n:02d}.png") for n in range(22)]

        prep = _prep(srcs, tmp_path)

        assert len(prep.images) == image_attachments.MAX_IMAGES
        late = _block(prep, "i21.png")
        assert late.kind == KIND_OMITTED
        assert "20" in late.detail
        assert prep.attachments[21] == str(srcs[21])

    def test_the_encoded_byte_budget_stops_later_images(self, tmp_path, monkeypatch, ocr_calls):
        srcs = []
        for n in range(4):
            p = tmp_path / f"n{n}.png"
            _noise((256, 256)).save(p, "PNG")
            srcs.append(p)
        one = encoded_len(srcs[0].stat().st_size)
        monkeypatch.setattr(image_attachments, "MAX_ENCODED_BYTES", int(one * 2.2))

        prep = _prep(srcs, tmp_path)

        assert 0 < len(prep.images) < 4
        omitted = [b for b in prep.ocr_blocks if b.kind == KIND_OMITTED]
        assert omitted
        assert any("budget" in b.detail or "byte" in b.detail for b in omitted)

    def test_the_normalization_time_budget_refuses_before_decoding(
        self, tmp_path, monkeypatch, no_ocr
    ):
        src = _png(tmp_path / "late.png")
