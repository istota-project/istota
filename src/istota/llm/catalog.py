"""The model catalogue: one record per model, layered from several sources.

Every surface that needs to know about a model (its context window, prices,
capabilities, family) reads a ``ModelInfo`` from here. The records come from
layers, highest first:

    operator overrides            partial, merged field by field
            ▼
    operator-declared models      full records
            ▼
    discovered models             per provider (today: OpenRouter, installed by NativeBrain)
            ▼
    the shipped Anthropic file    ``llm/data/anthropic.json``, regenerated by
                                  ``scripts/update-anthropic-catalog.py``
            ▼
    conservative default          ``_DEFAULT``: 200k window, zero price

The layers are held in an immutable ``Catalogue`` snapshot, swapped whole when
one changes, so a reader never sees a half-built table. ``get_model_info`` keeps
its old signature and accepts a bare id or a ``provider/id`` reference.

A bare id is looked up before a reference: an OpenRouter id such as
``anthropic/claude-opus-4.8`` is that provider's own id, not a reference to the
shipped Anthropic record.
"""

from __future__ import annotations

import json
import threading
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field, fields, replace
from functools import lru_cache
from importlib.resources import files

SHIPPED_PROVIDER = "anthropic"

# The two names ``ModelInfo`` had before ``input`` and ``reasoning``; still
# accepted by the constructor, by ``replace`` and in overrides and caches.
LEGACY_FIELD_NAMES = frozenset({"supports_vision", "supports_thinking"})

PRICE_SOURCES = ("shipped", "discovered", "operator", "unknown")


@dataclass(frozen=True)
class PriceTier:
    """Prices for a request whose total input exceeds ``input_tokens_above``."""

    input_tokens_above: int
    input_price_per_mtok: float = 0.0
    output_price_per_mtok: float = 0.0
    cache_read_price_per_mtok: float = 0.0
    cache_write_price_per_mtok: float = 0.0


def _as_price_tier(value: PriceTier | Mapping) -> PriceTier:
    if isinstance(value, PriceTier):
        return value
    if isinstance(value, Mapping):
        return PriceTier(**value)
    raise TypeError(f"price tier must be a PriceTier or a mapping, not {type(value).__name__}")


@dataclass(frozen=True, init=False)
class ModelInfo:
    """Metadata for one model of one provider.

    ``id`` is the provider's own id; ``ref`` is ``provider/id``. ``effort_map``
    maps an effort level to the value sent on the wire; ``None`` marks the level
    unsupported and a missing key means the level name is sent as it is.
    """

    id: str
    context_window: int
    max_output_tokens: int
    input_price_per_mtok: float = 0.0  # USD per 1M input tokens
    output_price_per_mtok: float = 0.0
    cache_read_price_per_mtok: float = 0.0
    cache_write_price_per_mtok: float = 0.0
    supports_tools: bool = True
    supports_structured_outputs: bool = False
    provider: str = ""
    name: str = ""
    family: str | None = None
    released: str | None = None
    deprecated: bool = False
    input: tuple[str, ...] = ("text",)
    reasoning: bool = False
    effort_map: Mapping[str, str | None] = field(default_factory=dict, hash=False)
    price_source: str = "unknown"
    price_tiers: tuple[PriceTier, ...] = ()

    # Hand-written so ``supports_vision`` and ``supports_thinking`` keep working
    # as keywords: ``dataclasses.replace`` passes its changes through here, and
    # an explicit legacy keyword wins over the copied ``input`` / ``reasoning``.
    def __init__(
        self,
        id: str,
        context_window: int,
        max_output_tokens: int,
        input_price_per_mtok: float = 0.0,
        output_price_per_mtok: float = 0.0,
        cache_read_price_per_mtok: float = 0.0,
        cache_write_price_per_mtok: float = 0.0,
        supports_tools: bool = True,
        supports_structured_outputs: bool = False,
        provider: str = "",
        name: str = "",
        family: str | None = None,
        released: str | None = None,
        deprecated: bool = False,
        input: Iterable[str] = ("text",),
        reasoning: bool = False,
        effort_map: Mapping[str, str | None] | None = None,
        price_source: str = "unknown",
        price_tiers: Iterable[PriceTier | Mapping] = (),
        *,
        supports_vision: bool | None = None,
        supports_thinking: bool | None = None,
    ) -> None:
        inputs = tuple(input)
        if supports_vision is not None:
            inputs = tuple(m for m in inputs if m != "image")
            if supports_vision:
                inputs = inputs + ("image",)
        if supports_thinking is not None:
            reasoning = supports_thinking
        values = {
            "id": id,
            "context_window": context_window,
            "max_output_tokens": max_output_tokens,
            "input_price_per_mtok": input_price_per_mtok,
            "output_price_per_mtok": output_price_per_mtok,
            "cache_read_price_per_mtok": cache_read_price_per_mtok,
            "cache_write_price_per_mtok": cache_write_price_per_mtok,
            "supports_tools": supports_tools,
            "supports_structured_outputs": supports_structured_outputs,
            "provider": provider,
            "name": name or id,
            "family": family,
            "released": released,
            "deprecated": bool(deprecated),
            "input": inputs,
            "reasoning": bool(reasoning),
            "effort_map": dict(effort_map or {}),
            "price_source": price_source,
            "price_tiers": tuple(_as_price_tier(t) for t in price_tiers),
        }
        for key, value in values.items():
            object.__setattr__(self, key, value)

    @property
    def supports_vision(self) -> bool:
        return "image" in self.input

    @property
    def supports_thinking(self) -> bool:
        return self.reasoning

    @property
    def ref(self) -> str:
        return f"{self.provider}/{self.id}" if self.provider else self.id


_FIELD_NAMES = frozenset(f.name for f in fields(ModelInfo))

# Fields an override may set: everything but the identity.
_OVERRIDABLE_FIELDS = (_FIELD_NAMES - {"id", "provider"}) | LEGACY_FIELD_NAMES


def model_info_from_dict(raw: Mapping) -> ModelInfo:
    """Build a ``ModelInfo`` from a JSON-shaped mapping; unknown keys are dropped."""
    clean = {k: v for k, v in raw.items() if k in _FIELD_NAMES or k in LEGACY_FIELD_NAMES}
    return ModelInfo(**clean)


# The floor for an unknown model. 200k is a last resort that discovery covers in
# practice. Overflow from an over-large window is recoverable (≤2
# compact-and-retry); premature compaction from an under-large one is merely
# wasteful. Zero price → cost surfaces as unknown rather than wrong.
_DEFAULT = ModelInfo(id="unknown", context_window=200_000, max_output_tokens=16384)


def _clean_overrides(overrides: Mapping | None) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for key, raw in (overrides or {}).items():
        if not isinstance(key, str) or not isinstance(raw, Mapping):
            continue
        clean = {k: v for k, v in raw.items() if k in _OVERRIDABLE_FIELDS}
        if clean:
            out[key] = clean
    return out


def _with_provider(info: ModelInfo, provider: str) -> ModelInfo:
    return info if info.provider == provider else replace(info, provider=provider)


@dataclass(frozen=True)
class Catalogue:
    """An immutable snapshot of every layer, with lookups over it.

    Build one with ``build_catalogue``. The layer inputs are kept so a new
    snapshot can be built from this one with a single layer swapped.
    """

    shipped: tuple[ModelInfo, ...] = ()
    discovered: Mapping[str, tuple[ModelInfo, ...]] = field(default_factory=dict, hash=False)
    operator: Mapping[str, tuple[ModelInfo, ...]] = field(default_factory=dict, hash=False)
    overrides: Mapping[str, Mapping] = field(default_factory=dict, hash=False)
    _by_ref: Mapping[str, ModelInfo] = field(default_factory=dict, hash=False, repr=False)
    _by_id: Mapping[str, ModelInfo] = field(default_factory=dict, hash=False, repr=False)

    def get(self, key: str) -> ModelInfo:
        """The record for a bare id or a ``provider/id`` reference.

        A miss returns the conservative default carrying ``key`` as its id.
        An override keyed by either the queried key or the record's ref applies.
        """
        info = self._by_id.get(key) or self._by_ref.get(key)
        override = self.overrides.get(key)
        if override is None and info is not None:
            override = self.overrides.get(info.ref)
        if info is None:
            # A legacy ``[brain.native.model_overrides]`` entry may describe a
            # model no layer has; it applies over the default, as it always did.
            info = replace(_DEFAULT, id=key, name=key)
        if override:
            info = replace(info, **override)
        return info

    def models(self, provider: str | None = None) -> tuple[ModelInfo, ...]:
        """Every known model (overrides applied), optionally for one provider."""
        out = []
        for ref, info in self._by_ref.items():
            if provider is None or info.provider == provider:
                out.append(self.get(ref))
        return tuple(out)

    def refs(self) -> tuple[str, ...]:
        return tuple(self._by_ref)

    def latest(self, family: str, provider: str = SHIPPED_PROVIDER) -> ModelInfo | None:
        """The newest non-deprecated model of ``family`` for ``provider``, by ``released``."""
        best: ModelInfo | None = None
        for info in self.models(provider):
            if info.family != family or info.deprecated:
                continue
            if best is None or (info.released or "", info.id) > (best.released or "", best.id):
                best = info
        return best


def build_catalogue(
    *,
    shipped: Iterable[ModelInfo] = (),
    discovered: Mapping[str, Iterable[ModelInfo]] | None = None,
    operator: Mapping[str, Iterable[ModelInfo]] | None = None,
    overrides: Mapping | None = None,
) -> Catalogue:
    """Merge the layers into a snapshot. A higher layer replaces a lower one by ref."""
    shipped_t = tuple(_with_provider(m, m.provider or SHIPPED_PROVIDER) for m in shipped)
    discovered_t = {
        p: tuple(_with_provider(m, p) for m in models) for p, models in (discovered or {}).items()
    }
    operator_t = {
        p: tuple(_with_provider(m, p) for m in models) for p, models in (operator or {}).items()
    }

    # Lowest layer first, so a higher one overwrites by ref.
    by_ref: dict[str, ModelInfo] = {}
    for info in shipped_t:
        by_ref[info.ref] = info
    for models in discovered_t.values():
        for info in models:
            by_ref[info.ref] = info
    for models in operator_t.values():
        for info in models:
            by_ref[info.ref] = info

    # Highest layer first, so the first record for an id wins. The shipped
    # file is reached by ref only: a bare Claude id on native today goes to an
    # endpoint no layer describes, and shipped capabilities would change what
    # native sends it. Bare ids reach it once a provider owns them.
    by_id: dict[str, ModelInfo] = {}
    ordered = [m for ms in operator_t.values() for m in ms]
    ordered += [m for ms in discovered_t.values() for m in ms]
    for info in ordered:
        by_id.setdefault(info.id, by_ref[info.ref])

    return Catalogue(
        shipped=shipped_t,
        discovered=discovered_t,
        operator=operator_t,
        overrides=_clean_overrides(overrides),
        _by_ref=by_ref,
        _by_id=by_id,
    )


def parse_shipped(document: Mapping) -> tuple[ModelInfo, ...]:
    """The records of a shipped catalogue document (``{"models": [...]}``)."""
    out = []
    for raw in document.get("models", []):
        record = dict(raw)
        record["provider"] = SHIPPED_PROVIDER
        record["price_source"] = "shipped"
        out.append(model_info_from_dict(record))
    return tuple(out)


@lru_cache(maxsize=1)
def shipped_anthropic_models() -> tuple[ModelInfo, ...]:
    """The committed Anthropic catalogue, read once per process."""
    text = files("istota.llm").joinpath("data/anthropic.json").read_text()
    return parse_shipped(json.loads(text))


def latest_shipped_id(family: str) -> str:
    """The id of the newest current shipped Anthropic model in ``family``.

    Raises ``LookupError`` when the family has none; the data test keeps the
    committed file from getting there.
    """
    info = build_catalogue(shipped=shipped_anthropic_models()).latest(family)
    if info is None:
        raise LookupError(f"the shipped Anthropic catalogue has no current {family!r} model")
    return info.id


# --- the process snapshot ---------------------------------------------------

_LOCK = threading.Lock()
_CURRENT: Catalogue | None = None


def current_catalogue() -> Catalogue:
    """The process's snapshot, built on first use from the shipped file."""
    snapshot = _CURRENT
    if snapshot is not None:
        return snapshot
    with _LOCK:
        return _current_locked()


def _current_locked() -> Catalogue:
    global _CURRENT
    if _CURRENT is None:
        _CURRENT = build_catalogue(shipped=shipped_anthropic_models())
    return _CURRENT


def _swap(**layers) -> None:
    global _CURRENT
    with _LOCK:
        cur = _current_locked()
        inputs = {
            "shipped": cur.shipped,
            "discovered": cur.discovered,
            "operator": cur.operator,
            "overrides": cur.overrides,
        }
        inputs.update(layers)
        _CURRENT = build_catalogue(**inputs)


def set_model_overrides(overrides: dict | None) -> None:
    """Replace the override layer (``[brain.native.model_overrides]``).

    Each value is a partial record; unknown keys are dropped. ``{}`` / ``None``
    clears the layer.
    """
    _swap(overrides=overrides or {})


def set_fetched_catalog(entries: dict[str, ModelInfo] | None) -> None:
    """Install (or clear) the OpenRouter discovery layer.

    NativeBrain fetches only from OpenRouter today, so the entries are recorded
    under the ``openrouter`` provider. ``None`` / ``{}`` clears the layer.
    """
    models = tuple(v for v in (entries or {}).values() if isinstance(v, ModelInfo))
    _swap(discovered={"openrouter": models} if models else {})


def get_model_info(model_id: str) -> ModelInfo:
    """Return the record for a bare id or a ``provider/id`` reference."""
    return current_catalogue().get(model_id)
