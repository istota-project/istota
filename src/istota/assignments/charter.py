"""The charter: validating its fields, the slug, the rendered text and the directory.

The charter is the `assignments` row plus its `assignment_items` and
`assignment_frozen` rows. The DB is the only authority; `render` turns the rows
into the markdown the user approves and reads, and `CHARTER.md` is that text
behind a fixed header line. The host writes `CHARTER.md` after every charter
change and never reads it back.

Every `validate_*` function returns the normalized value or raises
`CharterError(code, message)`, with `code` one of the CLI's error codes:
`invalid_charter`, `invalid_validator`, `invalid_duration`, `over_ceiling`,
`deadline_passed`, and `too_many_active` from `budget`.

The assignment directory is `{bot_dir}/assignments/<slug>/` under
`Config.workspace_root(user_id)`, created and written by descriptor through
`sandbox.confined` and `storage.write_regular_file`, since a wake can write
anything below the bot directory.
"""

from __future__ import annotations

import hashlib
import logging
import math
import os
import re
import sqlite3
from datetime import date, datetime, timezone, tzinfo
from typing import TYPE_CHECKING, Any, Sequence

from istota import storage
from istota.assignments import store, validators
from istota.sandbox import confined

if TYPE_CHECKING:
    from istota.config import AssignmentsConfig, Config

logger = logging.getLogger("istota.assignments.charter")

DEFAULT_PER_WAKE_MINUTES = 20
DEFAULT_PER_WAKE_TURNS = 60
TITLE_MAX_CHARS = 200
GOAL_MAX_CHARS = 8000
ITEM_MAX_CHARS = 500
FROZEN_NAME_MAX_CHARS = 64
FROZEN_VALUE_MAX_CHARS = 500
SLUG_MAX_CHARS = 48

ASSIGNMENTS_DIR = "assignments"
CHARTER_FILE = "CHARTER.md"
SCRATCHPAD_FILE = "SCRATCHPAD.md"
CHARTER_FILE_HEADER = (
    "<!-- Generated by Istota from the assignment record. "
    "Edits here are not read; change the charter in chat. -->"
)
SCRATCHPAD_SEED = (
    "# Scratchpad\n\n"
    "## Now\n\n"
    "## Done\n\n"
    "## Thinking\n\n"
    "## Rejected\n\n"
    "## Problems\n\n"
    "## Findings\n"
)

# A date-only deadline is the end of that day, so it renders back as the date.
_END_OF_DAY_SUFFIX = "T23:59:59.999Z"
_SLUG_DROP = re.compile(r"[^a-z0-9]+")
_DURATION = re.compile(r"(\d{1,6})([mhd])")
_DURATION_UNITS = {"m": 1, "h": 60, "d": 1440}
_DURATION_MAX_MINUTES = 366 * 1440
MODEL_MAX_CHARS = 100


class CharterError(ValueError):
    """A refused charter value. `code` is the CLI error code; the message is plain text."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------


def _one_line(value: object) -> str:
    return " ".join(str(value or "").split())


def _bounded_text(value: object, *, field: str, limit: int, required: bool) -> str:
    text = str(value or "").strip()
    if required and not text:
        raise CharterError("invalid_charter", f"{field} is required")
    if len(text) > limit:
        raise CharterError("invalid_charter", f"{field} is longer than {limit} characters")
    return text


def validate_title(value: object) -> str:
    text = _one_line(value)
    if not text:
        raise CharterError("invalid_charter", "title is required")
    if len(text) > TITLE_MAX_CHARS:
        raise CharterError("invalid_charter", f"title is longer than {TITLE_MAX_CHARS} characters")
    return text


def validate_goal(value: object) -> str:
    return _bounded_text(value, field="goal", limit=GOAL_MAX_CHARS, required=True)


def validate_autonomy(value: object) -> str:
    return _bounded_text(value, field="autonomy", limit=GOAL_MAX_CHARS, required=False)


def _positive_int(value: object, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise CharterError("invalid_charter", f"{field} must be a whole number of at least 1")
    return value


def validate_budget(
    cfg: "AssignmentsConfig",
    *,
    max_cost_usd: object,
    max_wakes: object,
    per_wake_minutes: object = None,
    per_wake_turns: object = None,
) -> dict[str, Any]:
    """The budget JSON for the row, held to the deployment ceilings in `[assignments]`."""
    if isinstance(max_cost_usd, bool) or not isinstance(max_cost_usd, (int, float)):
        raise CharterError("invalid_charter", "the cost budget must be a number of dollars")
    cost = float(max_cost_usd)
    if not math.isfinite(cost) or cost <= 0:
        raise CharterError("invalid_charter", "the cost budget must be more than zero")
    wakes = _positive_int(max_wakes, "max_wakes")
    minutes = _positive_int(
        DEFAULT_PER_WAKE_MINUTES if per_wake_minutes is None else per_wake_minutes, "per_wake_minutes",
    )
    turns = _positive_int(
        DEFAULT_PER_WAKE_TURNS if per_wake_turns is None else per_wake_turns, "per_wake_turns",
    )
    if cost > cfg.max_cost_usd_per_assignment:
        raise CharterError(
            "over_ceiling",
            f"the cost budget is over this deployment's ceiling of ${cfg.max_cost_usd_per_assignment:.2f}",
        )
    if wakes > cfg.max_wakes_per_assignment:
        raise CharterError(
            "over_ceiling",
            f"max_wakes is over this deployment's ceiling of {cfg.max_wakes_per_assignment}",
        )
    return {
        "max_cost_usd": cost,
        "max_wakes": wakes,
        "per_wake_minutes": minutes,
        "per_wake_turns": turns,
    }


def iso_z(moment: datetime) -> str:
    """`db.iso_utc_now`'s format for a given moment."""
    utc = moment.astimezone(timezone.utc)
    return utc.strftime("%Y-%m-%dT%H:%M:%S.") + f"{utc.microsecond // 1000:03d}Z"


def parse_time(value: object, *, tz: tzinfo = timezone.utc) -> datetime:
    """An ISO 8601 date and time; one with no offset is read in `tz`.

    Raises ValueError for anything else, a bare date included.
    """
    text = str(value or "").strip()
    if len(text) <= 10:
        raise ValueError("not a date and time")
    moment = datetime.fromisoformat(text)
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=tz)
    return moment


def validate_deadline(
    value: object, *, now: datetime | None = None, tz: tzinfo = timezone.utc,
) -> str:
    """An ISO-Z deadline. A bare date is the end of that day in UTC; a time with no
    offset is read in `tz` (the user's timezone, which the caller supplies)."""
    text = str(value or "").strip()
    now = now or datetime.now(timezone.utc)
    try:
        if len(text) == 10:
            day = date.fromisoformat(text)
            stored = day.isoformat() + _END_OF_DAY_SUFFIX
            moment = datetime.fromisoformat(stored.replace("Z", "+00:00"))
        else:
            moment = parse_time(text, tz=tz)
            stored = iso_z(moment)
    except ValueError:
        raise CharterError(
            "invalid_charter", "the deadline must be a date (YYYY-MM-DD) or an ISO 8601 time",
        ) from None
    if moment <= now:
        raise CharterError("deadline_passed", "the deadline is in the past")
    return stored


def validate_cadence(cfg: "AssignmentsConfig", minutes: object) -> int:
    """The default check-in interval, no shorter than the wake floor."""
    value = _positive_int(minutes, "cadence")
    if value < cfg.min_wake_interval_minutes:
        raise CharterError(
            "invalid_charter",
            f"the check-in interval must be at least {cfg.min_wake_interval_minutes} minutes",
        )
    return value


def parse_duration_minutes(value: object) -> int:
    """`Nm`, `Nh` or `Nd` as whole minutes; the inverse of `_duration`.

    Raises `CharterError("invalid_duration")`. The tree's only other relative
    parser, `skills/tasks.parse_since`, turns a window into a past timestamp
    rather than a length, so it is not this.
    """
    match = _DURATION.fullmatch(str(value or "").strip().lower())
    if match is None:
        raise CharterError("invalid_duration", "a duration is a number with m, h or d, such as 30m, 6h or 2d")
    minutes = int(match.group(1)) * _DURATION_UNITS[match.group(2)]
    if minutes < 1 or minutes > _DURATION_MAX_MINUTES:
        raise CharterError("invalid_duration", "a duration must be between 1 minute and 366 days")
    return minutes


def validate_model(value: object) -> str | None:
    text = _one_line(value)
    if not text:
        return None
    if len(text) > MODEL_MAX_CHARS:
        raise CharterError("invalid_charter", f"the model name is longer than {MODEL_MAX_CHARS} characters")
    return text


def validate_effort(value: object) -> str | None:
    from istota.brain._aliases import EFFORT_LEVELS

    text = _one_line(value).lower()
    if not text:
        return None
    if text not in EFFORT_LEVELS:
        raise CharterError("invalid_charter", f"effort must be one of {', '.join(sorted(EFFORT_LEVELS))}")
    return text


def validate_item(text: object, kind: object, validator: object) -> tuple[str, dict[str, Any] | None]:
    """`(text, normalized spec)` for a done-when item. Only `item add` writes a spec."""
    clean = _one_line(text)
    if not clean:
        raise CharterError("invalid_charter", "the item needs text")
    if len(clean) > ITEM_MAX_CHARS:
        raise CharterError("invalid_charter", f"the item is longer than {ITEM_MAX_CHARS} characters")
    if kind not in ("mechanical", "confirmed"):
        raise CharterError("invalid_charter", "kind must be mechanical or confirmed")
    if kind == "confirmed":
        if validator is not None:
            raise CharterError("invalid_validator", "a confirmed item takes no check")
        return clean, None
    if validator is None:
        raise CharterError("invalid_validator", "a mechanical item needs a check")
    try:
        return clean, validators.parse_spec(validator)
    except validators.InvalidValidator as exc:
        raise CharterError("invalid_validator", str(exc)) from None


def validate_frozen(name: object, value: object) -> tuple[str, str]:
    clean_name = _one_line(name)
    clean_value = _one_line(value)
    if not clean_name or len(clean_name) > FROZEN_NAME_MAX_CHARS:
        raise CharterError(
            "invalid_charter", f"a frozen commitment needs a name of 1 to {FROZEN_NAME_MAX_CHARS} characters",
        )
    if not clean_value or len(clean_value) > FROZEN_VALUE_MAX_CHARS:
        raise CharterError(
            "invalid_charter", f"a frozen commitment needs a value of 1 to {FROZEN_VALUE_MAX_CHARS} characters",
        )
    return clean_name, clean_value


