# Slug and directory names
# ---------------------------------------------------------------------------


def slugify(title: str) -> str:
    """Lowercase ASCII letters and digits joined by `-`. Also the directory name."""
    slug = _SLUG_DROP.sub("-", str(title).lower()).strip("-")
    slug = slug[:SLUG_MAX_CHARS].strip("-")
    return slug or "assignment"


def unique_slug(conn: sqlite3.Connection, user_id: str, title: str) -> str:
    """`slugify(title)`, with `-2`, `-3`, ... appended past the user's existing slugs."""
    base = slugify(title)
    candidate = base
    n = 2
    while store.get_assignment_by_slug(conn, user_id, candidate) is not None:
        candidate = f"{base}-{n}"
        n += 1
    return candidate


def dir_relpath(slug: str) -> str:
    """The row's `dir_relpath`: relative to the bot directory."""
    return f"{ASSIGNMENTS_DIR}/{slug}"


def _dir_parts(config: "Config", assignment: store.Assignment) -> list[str]:
    return [config.bot_dir_name, *assignment.dir_relpath.split("/")]


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def _money(value: object) -> str:
    try:
        return f"${float(value):.2f}"
    except (TypeError, ValueError):
        return "$?"


def _duration(minutes: int) -> str:
    if minutes % 1440 == 0:
        return f"{minutes // 1440}d"
    if minutes % 60 == 0:
        return f"{minutes // 60}h"
    return f"{minutes}m"


def _deadline(value: str) -> str:
    if value.endswith(_END_OF_DAY_SUFFIX):
        return value[:10]
    try:
        moment = datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(timezone.utc)
    except ValueError:
        return _one_line(value)
    return moment.strftime("%Y-%m-%d %H:%M UTC")


def _budget_line(assignment: store.Assignment) -> str:
    budget = assignment.budget
    line = (
        f"{_money(budget.get('max_cost_usd'))}, {budget.get('max_wakes')} wakes, "
        f"{budget.get('per_wake_minutes', DEFAULT_PER_WAKE_MINUTES)} minutes and "
        f"{budget.get('per_wake_turns', DEFAULT_PER_WAKE_TURNS)} turns per wake."
    )
    if assignment.deadline:
        line += f" Deadline {_deadline(assignment.deadline)}."
    line += f" Default check-in every {_duration(assignment.cadence_minutes)}."
    return line


def _item_line(position: int, item: store.Item) -> str:
    line = f"{position}. [{item.kind}] {_one_line(item.text)}"
    if item.kind == "mechanical" and item.validator:
        line += f" (check: {validators.describe(item.validator)})"
    return line


def render(
    assignment: store.Assignment, items: Sequence[store.Item], frozen: Sequence[store.Frozen],
) -> str:
    """The charter as markdown: the activation preview, `CHARTER.md`'s body, the wake's charter.

    No state: `CHARTER.md` is rewritten only on a charter change, so a state
    here would go stale on every transition (ISSUE-837). `assignment show` has it.
    """
    lines = [
        f"# {_one_line(assignment.title)}",
        "",
        f"Assignment {assignment.id} · created {assignment.created_at[:10]}",
        "",
        "## Goal",
        assignment.goal.strip(),
        "",
        "## Done when",
    ]
    if items:
        lines.extend(_item_line(n, item) for n, item in enumerate(items, start=1))
    else:
        lines.append("None yet.")
    lines += ["", "## May do without asking", assignment.autonomy.strip() or "Nothing beyond the charter."]
    lines += ["", "## Frozen commitments"]
    if frozen:
        lines.extend(f"- {_one_line(f.name)}: {_one_line(f.value)}" for f in frozen)
    else:
        lines.append("None.")
    lines += ["", "## Budget", _budget_line(assignment)]
    return "\n".join(lines) + "\n"


def render_current(conn: sqlite3.Connection, assignment_id: int) -> str:
    """`render` over the rows as they are now."""
    assignment = store.get_assignment(conn, assignment_id)
    if assignment is None:
        raise LookupError(f"no assignment {assignment_id}")
    return render(assignment, store.list_items(conn, assignment_id), store.list_frozen(conn, assignment_id))


def charter_digest(conn: sqlite3.Connection, assignment_id: int) -> str:
    """sha256 of the rendered charter: what an activation approval is bound to."""
    return hashlib.sha256(render_current(conn, assignment_id).encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# The directory and its files
# ---------------------------------------------------------------------------


def open_assignment_dir(config: "Config", assignment: store.Assignment) -> int | None:
    """A descriptor on the assignment directory, created if missing; None when refused.

    Walked with no link followed from `Config.workspace_root`. The caller closes it.
    """
    root = config.workspace_root(assignment.user_id)
    if root is None:
        logger.warning("assignment directory skipped: no workspace assignment_id=%s", assignment.id)
        return None
    try:
        return confined.open_or_create_dirs(root, _dir_parts(config, assignment))
    except (OSError, ValueError) as exc:
        logger.warning(
            "assignment directory refused assignment_id=%s error=%s", assignment.id, type(exc).__name__,
        )
        return None


def _write_charter_at(dir_fd: int, rendered: str) -> bool:
    return storage.write_regular_file(
        CHARTER_FILE, f"{CHARTER_FILE_HEADER}\n\n{rendered}", dir_fd=dir_fd,
    )


def create_directory(config: "Config", conn: sqlite3.Connection, assignment: store.Assignment) -> bool:
    """Create `{bot_dir}/assignments/<slug>/` with a seed `SCRATCHPAD.md` and `CHARTER.md`.

    An existing scratchpad is left alone. False when the directory could not be
    made or a file not written; the DB state stands either way, and the next
    charter change rewrites `CHARTER.md`.
    """
    dir_fd = open_assignment_dir(config, assignment)
    if dir_fd is None:
        return False
    try:
        ok = True
        try:
            os.stat(SCRATCHPAD_FILE, dir_fd=dir_fd, follow_symlinks=False)
        except FileNotFoundError:
            ok = storage.write_regular_file(SCRATCHPAD_FILE, SCRATCHPAD_SEED, dir_fd=dir_fd)
        rendered = render(
            assignment, store.list_items(conn, assignment.id), store.list_frozen(conn, assignment.id),
        )
        return _write_charter_at(dir_fd, rendered) and ok
    finally:
        os.close(dir_fd)


def rewrite_charter_file(config: "Config", conn: sqlite3.Connection, assignment_id: int) -> str:
    """Re-render the charter, write `CHARTER.md`, and return the rendered text.

    The text is returned whether or not the write landed, since the DB is the
    authority and the caller shows the user the charter either way.
    """
    assignment = store.get_assignment(conn, assignment_id)
    if assignment is None:
        raise LookupError(f"no assignment {assignment_id}")
    rendered = render(assignment, store.list_items(conn, assignment_id), store.list_frozen(conn, assignment_id))
    dir_fd = open_assignment_dir(config, assignment)
    if dir_fd is not None:
        try:
            if not _write_charter_at(dir_fd, rendered):
                logger.warning("CHARTER.md not written assignment_id=%s", assignment_id)
        finally:
            os.close(dir_fd)
    return rendered
